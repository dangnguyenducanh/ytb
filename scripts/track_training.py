"""Write a readable, auto-refreshing progress log for a running `ytb.train` run.

Reads the nohup log without touching the training process, rewrites a Markdown file every
--interval seconds while the run is alive, and writes a final summary when it ends.

uv run python scripts/track_training.py --log runs/train.log --out docs/training/<date>-ytb-summarizer-progress.md
"""

import argparse
import ast
import re
import subprocess
import time
from datetime import datetime, timedelta
from pathlib import Path

# training bar: no description prefix, no cursor-up escape (eval bars end with \x1b[A)
BAR = re.compile(r"^\s*\d+%\|[^|]*\|\s*(\d+)/(\d+) \[([\d:]+)<([\d:?]+),\s*([\d.]+)(s/it|it/s)\]")
DICT = re.compile(r"\{[^{}]*\}")
PEAK = re.compile(r"peak_gpu_gb=([\d.]+)")


def _secs(t: str) -> int | None:
    if "?" in t:
        return None
    s = 0
    for part in t.split(":"):
        s = s * 60 + int(part)
    return s


def _hms(s) -> str:
    return "—" if s is None else str(timedelta(seconds=int(s)))


def parse(text: str) -> dict:
    st = {"step": 0, "total": None, "elapsed": None, "eta": None, "s_per_step": None,
          "train": [], "evals": [], "final": {}, "peak": None, "error": None}
    for seg in re.split(r"[\r\n]", text):
        bar = BAR.match(seg)
        if bar and "\x1b" not in seg:
            st.update(step=int(bar[1]), total=int(bar[2]), elapsed=_secs(bar[3]), eta=_secs(bar[4]),
                      s_per_step=float(bar[5]) if bar[6] == "s/it" else 1 / float(bar[5]))
            continue
        for d in DICT.findall(seg):
            try:
                row = ast.literal_eval(d)
            except (ValueError, SyntaxError):
                continue
            if not isinstance(row, dict):
                continue
            row = {"step": st["step"], "elapsed": st["elapsed"], **row}
            if "loss" in row:
                st["train"].append(row)
            elif "eval_loss" in row:
                st["evals"].append(row)
            elif "train_runtime" in row:
                st["final"] = row
    if peak := PEAK.search(text):
        st["peak"] = float(peak[1])
    if (tb := text.rfind("Traceback")) != -1:
        st["error"] = text[tb:].strip().splitlines()[-1][:300]
    return st


def _pids(pattern: str) -> list[int]:
    out = subprocess.run(["pgrep", "-f", pattern], capture_output=True, text=True).stdout
    return [int(p) for p in out.split()]


def _cmdline(pids: list[int]) -> str:
    args = [subprocess.run(["ps", "-o", "args=", "-p", str(p)], capture_output=True, text=True).stdout.strip()
            for p in pids]
    return max(args, key=len, default="—")


def _gpu_mib(pids: list[int]) -> int | None:
    out = subprocess.run(["nvidia-smi", "--query-compute-apps=pid,used_memory", "--format=csv,noheader,nounits"],
                         capture_output=True, text=True).stdout
    used = [int(mem) for pid, mem in (line.split(", ") for line in out.strip().splitlines() if line)
            if int(pid) in pids]
    return sum(used) if used else None


def render(st: dict, status: str, log: Path, interval: int, cmd: str, gpu_now, gpu_peak) -> str:
    total, now = st["total"], datetime.now()
    pct = f" ({100 * st['step'] / total:.0f}%)" if total else ""
    finish = (now + timedelta(seconds=st["eta"])).strftime("%H:%M") if st["eta"] and status == "running" else "—"
    speed = f"{st['s_per_step']:.2f} s/step" if st["s_per_step"] else "—"
    out = [
        "# Training progress — ytb-summarizer (Qwen3-0.6B full fine-tune)",
        "",
        f"_Generated by `scripts/track_training.py` from `{log}`, refreshed every {interval} s while training runs._",
        "",
        "| | |",
        "|---|---|",
        f"| Status | **{status}** |",
        f"| Updated | {now:%Y-%m-%d %H:%M:%S} |",
        f"| Step | {st['step']} / {total or '—'}{pct} |",
        f"| Elapsed / remaining | {_hms(st['elapsed'])} / {_hms(st['eta'])} (finish ≈ {finish}) |",
        f"| Speed | {speed} |",
        f"| GPU (training process) | {gpu_now if gpu_now is not None else '—'} MiB now · {gpu_peak or '—'} MiB peak seen |",
        f"| Command | `{cmd}` |",
    ]
    if st["final"]:
        f = st["final"]
        out.append(f"| Result | train_loss {f.get('train_loss', '—')} · runtime {_hms(float(f.get('train_runtime', 0)))} |")
    if st["peak"] is not None:
        out.append(f"| peak_gpu_gb (torch) | {st['peak']} |")
    if st["error"]:
        out.append(f"| Error | `{st['error']}` |")

    out += ["", "## Validation loss", "", "| step | epoch | eval_loss | elapsed |", "|---:|---:|---:|---:|"]
    out += [f"| {r['step']} | {r.get('epoch', '')} | {r['eval_loss']} | {_hms(r['elapsed'])} |" for r in st["evals"]]
    out += ["", "## Training loss (logged every 10 steps)", "",
            "| step | epoch | loss | grad_norm | learning_rate | elapsed |", "|---:|---:|---:|---:|---:|---:|"]
    out += [f"| {r['step']} | {r.get('epoch', '')} | {r['loss']} | {r.get('grad_norm', '')} | "
            f"{r.get('learning_rate', '')} | {_hms(r['elapsed'])} |" for r in st["train"]]
    return "\n".join(out) + "\n"


def main(argv: list[str] | None = None) -> None:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--log", default="runs/train.log")
    p.add_argument("--out", required=True)
    p.add_argument("--interval", type=int, default=60)
    p.add_argument("--pattern", default="[y]tb.train", help="pgrep -f pattern for the training process")
    a = p.parse_args(argv)
    log, out = Path(a.log), Path(a.out)
    out.parent.mkdir(parents=True, exist_ok=True)

    cmd, gpu_now, gpu_peak = "—", None, 0
    while True:
        pids = _pids(a.pattern)
        if pids:
            cmd = _cmdline(pids)
            gpu_now = _gpu_mib(pids)
            gpu_peak = max(gpu_peak, gpu_now or 0)
        st = parse(log.read_text(encoding="utf-8", errors="replace") if log.exists() else "")
        if pids:
            status = "running"
        else:
            status = "finished" if st["final"] or st["peak"] is not None else "failed" if st["error"] else "stopped"
        out.write_text(render(st, status, log, a.interval, cmd, gpu_now if pids else None, gpu_peak))
        if not pids:
            print(f"training {status}; wrote {out}")
            return
        time.sleep(a.interval)


if __name__ == "__main__":
    main()
